/**
 * NF-5 test-vector generator.
 *
 * Emits the published artifacts that the PROTOCOL-profile assertions run against. This file
 * imports the reference implementation; the tests that consume its output do not. That split
 * is the whole point of NF-5 §4.2: an implementer who reuses none of `broker/src` must still
 * be assessable, and they can only be assessed against artifacts.
 *
 * WHAT THIS DOES AND DOES NOT ESTABLISH. The vectors are produced by the reference
 * implementation, so a defect in that implementation is faithfully reproduced in the vectors.
 * The PROTOCOL tests defend against that in the only way artifacts can: they re-derive every
 * cryptographic claim with independent code (raw WebCrypto Ed25519 and a separately written
 * JCS canonicaliser), and they check structural properties against the SPECIFICATION rather
 * than against the generator. A signature the reference computed wrongly fails the independent
 * check. A field the specification forbids fails the vocabulary check. What they cannot catch
 * is a case the reference and the spec are wrong about in the same direction — which is why
 * the negative vectors below are generated by deliberate post-hoc tampering rather than by
 * asking the implementation to produce something invalid.
 *
 * Regenerate with:  node conformance/vectors/generate.js
 * Vectors are committed so the suite runs offline and so a change to them shows up in review.
 */

import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { FIELDS, FIELD_CLASSES, NON_TRANSACTABLE, DPPA_PURPOSES, COUNTERPARTY_CLASSES } from '../../broker/src/fields.js'
import { generatePseudonymSalt } from '../../broker/src/vin.js'
import {
  SCHEMA_VERSION,
  GRANT_KEYS,
  MAX_GRANT_DURATION_S,
  MAX_DELEGATION_DEPTH,
  buildGrant,
  signGrant,
  mintDelegatedGrant,
  generateSigningKeyPair,
  exportPublicKeyBase64url,
  revocationKeyIdFromPublicKey,
  deriveGrantCommitment,
} from '../../broker/src/nf2-grant.js'
import {
  DEFAULT_MAX_DECISION_AGE_S,
  MAX_PERMITTED_DECISION_AGE_S,
  buildRevocation,
  signRevocation,
} from '../../broker/src/nf4-revocation.js'

const HERE = dirname(fileURLToPath(import.meta.url))

// Fixed inputs. The generator must be reproducible in everything except key material, so
// timestamps are pinned rather than read from the clock.
const ISSUED_AT = 1_800_000_000
const VIN = '1M8GDM9AXKP042788' // the ISO 3779 standard's own worked example
const SALT = generatePseudonymSalt()

function b64urlToBytes(s) {
  return Buffer.from(s.replace(/-/g, '+').replace(/_/g, '/'), 'base64')
}

async function main() {
  const owner = await generateSigningKeyPair()
  const insurer = await generateSigningKeyPair()
  const fleet = await generateSigningKeyPair()
  const contractor = await generateSigningKeyPair()
  const revoker = await generateSigningKeyPair()

  const ownerPub = await exportPublicKeyBase64url(owner.publicKey)
  const insurerPub = await exportPublicKeyBase64url(insurer.publicKey)
  const fleetPub = await exportPublicKeyBase64url(fleet.publicKey)
  const contractorPub = await exportPublicKeyBase64url(contractor.publicKey)
  const revocationKeyId = await revocationKeyIdFromPublicKey(
    b64urlToBytes(await exportPublicKeyBase64url(revoker.publicKey)),
  )

  const vectors = []

  // ---------------------------------------------------------------- GC: a valid root grant
  const root = await signGrant(
    await buildGrant({
      vin: VIN,
      pseudonymSalt: SALT,
      pseudonymEpoch: 0,
      fields: ['state_of_charge_pct', 'state_of_health_pct'],
      purpose: 'dppa-2721b-6',
      counterpartyClass: 'insurer',
      counterpartyKey: insurerPub,
      revocationKeyId,
      issuedAt: ISSUED_AT,
      durationSeconds: 7 * 24 * 60 * 60,
    }),
    owner.privateKey,
  )
  vectors.push({
    id: 'GC-VALID-ROOT',
    description: 'A well-formed root grant signed by the owner.',
    group: 'GC',
    expected: 'valid',
    signer_public_key: ownerPub,
    grant: root,
    grant_commitment: await deriveGrantCommitment(root),
  })

  // ------------------------------------------------------------- GC: tampered after signing
  const tamperedField = { ...root, fields: [...root.fields, 'odometer_km'].sort() }
  vectors.push({
    id: 'GC-TAMPER-FIELDS',
    description: 'The signed grant with an extra field appended after signing. The signature is unchanged.',
    group: 'GC',
    expected: 'invalid',
    reason: 'signature does not cover the widened field set',
    signer_public_key: ownerPub,
    grant: tamperedField,
  })

  const tamperedExpiry = { ...root, expires_at: root.expires_at + 86_400 }
  vectors.push({
    id: 'GC-TAMPER-EXPIRY',
    description: 'The signed grant with its expiry extended by a day after signing.',
    group: 'GC',
    expected: 'invalid',
    reason: 'signature does not cover the extended expiry',
    signer_public_key: ownerPub,
    grant: tamperedExpiry,
  })

  vectors.push({
    id: 'GC-WRONG-SIGNER',
    description: 'A valid grant checked against the counterparty key instead of the owner key.',
    group: 'GC',
    expected: 'invalid',
    reason: 'signature verifies only under the owner key that produced it',
    signer_public_key: insurerPub,
    grant: root,
  })

  // ------------------------------------------------------------------ DD: a delegation chain
  const delegable = await signGrant(
    await buildGrant({
      vin: VIN,
      pseudonymSalt: SALT,
      pseudonymEpoch: 0,
      fields: ['odometer_km', 'engine_hours'],
      purpose: 'dppa-2721b-2',
      counterpartyClass: 'fleet-operator',
      counterpartyKey: fleetPub,
      revocationKeyId,
      issuedAt: ISSUED_AT,
      durationSeconds: 30 * 24 * 60 * 60,
      delegationDepth: MAX_DELEGATION_DEPTH,
    }),
    owner.privateKey,
  )
  vectors.push({
    id: 'DD-ROOT-DEPTH-2',
    description: `A root grant authorising delegation to depth ${MAX_DELEGATION_DEPTH}.`,
    group: 'DD',
    expected: 'valid',
    signer_public_key: ownerPub,
    grant: delegable,
  })

  // The delegator signs the sub-grant, so the chain self-verifies from the root key alone.
  const sub = await signGrant(
    mintDelegatedGrant(delegable, {
      fields: ['odometer_km'],
      counterpartyClass: 'repair-independent',
      counterpartyKey: contractorPub,
      issuedAt: ISSUED_AT,
      durationSeconds: 7 * 24 * 60 * 60,
    }),
    fleet.privateKey,
  )
  vectors.push({
    id: 'DD-SUB-DEPTH-1',
    description: 'A sub-grant minted from DD-ROOT-DEPTH-2, signed by the delegator, depth decremented.',
    group: 'DD',
    expected: 'valid',
    signer_public_key: fleetPub,
    parent_id: 'DD-ROOT-DEPTH-2',
    grant: sub,
  })

  const forgedDepth = { ...sub, delegation_depth: sub.delegation_depth + 5 }
  vectors.push({
    id: 'DD-LAUNDERED-DEPTH',
    description: 'The sub-grant with its delegation depth raised after signing — depth laundering.',
    group: 'DD',
    expected: 'invalid',
    reason: 'there is no operation that adds depth; the signature does not cover the raised value',
    signer_public_key: fleetPub,
    grant: forgedDepth,
  })

  // ------------------------------------------------------------------ RV: revocation records
  const rootCommitment = await deriveGrantCommitment(root)
  const revokerPub = await exportPublicKeyBase64url(revoker.publicKey)

  const revokeRecord = await signRevocation(
    buildRevocation({
      scope: 'grant',
      target: rootCommitment,
      revocationPublicKey: revokerPub,
      issuedAt: ISSUED_AT + 3600,
      effectiveFrom: null,
      // Closed vocabulary: a revocation record is a disclosed witness, so its reason field
      // must not be able to carry free text and therefore personal information.
      reason: 'owner_withdrew',
    }),
    revoker.privateKey,
  )
  vectors.push({
    id: 'RV-REVOKE-GRANT',
    description: 'A grant-scope revocation signed by the OWNER-held revocation key.',
    group: 'RV',
    expected: 'valid',
    signer_public_key: revokerPub,
    record: revokeRecord,
    revokes: 'GC-VALID-ROOT',
  })

  vectors.push({
    id: 'RV-RETARGETED',
    description: 'The same revocation with its target rewritten after signing — pointing it at another grant.',
    group: 'RV',
    expected: 'invalid',
    reason: 'the signature covers the target; a revocation cannot be redirected',
    signer_public_key: revokerPub,
    record: { ...revokeRecord, target: rootCommitment.slice(0, -4) + 'dead' },
  })

  // -------------------------------------------------------------------- NT / VC properties
  // No vector may name a non-transactable field or carry a raw VIN; the PROTOCOL tests assert
  // that over EVERY vector, so these two groups are evidenced by the corpus as a whole rather
  // than by a dedicated entry.

  const out = {
    format: 'nf5-vectors/1',
    generated_for: SCHEMA_VERSION,
    note:
      'Signatures are Ed25519 over the JCS (RFC 8785) canonicalisation of the grant with the ' +
      '`signature` key omitted, UTF-8 encoded. Public keys and signatures are base64url raw ' +
      'bytes. A conformant implementation must reach the same verdict as `expected` for each ' +
      'vector without consulting this repository.',
    constants: {
      schema_version: SCHEMA_VERSION,
      grant_keys: GRANT_KEYS,
      max_grant_duration_s: MAX_GRANT_DURATION_S,
      max_delegation_depth: MAX_DELEGATION_DEPTH,
    },
    staleness: {
      // NF-4: a cached authorisation decision older than the bound MUST be re-derived, never
      // honoured. `age <= max_age_s` is permitted; strictly greater is not. A future-dated
      // decision is also refused — a clock that runs backwards must not extend a cache.
      rule: 'honour iff 0 <= (now - derived_at) <= max_age_s',
      default_max_decision_age_s: DEFAULT_MAX_DECISION_AGE_S,
      max_permitted_decision_age_s: MAX_PERMITTED_DECISION_AGE_S,
      cases: [
        { derived_at: ISSUED_AT, now: ISSUED_AT, max_age_s: 30, expected: 'honour' },
        { derived_at: ISSUED_AT, now: ISSUED_AT + 29, max_age_s: 30, expected: 'honour' },
        { derived_at: ISSUED_AT, now: ISSUED_AT + 30, max_age_s: 30, expected: 'honour' },
        { derived_at: ISSUED_AT, now: ISSUED_AT + 31, max_age_s: 30, expected: 're-derive' },
        { derived_at: ISSUED_AT, now: ISSUED_AT - 1, max_age_s: 30, expected: 're-derive' },
      ],
    },
    vectors,
  }

  const vocabulary = {
    format: 'nf5-vocabulary/1',
    note:
      'The closed NF-2 vocabulary as published. `non_transactable` entries have no grant type ' +
      'at all: they are not fields with a deny flag, and MUST NOT appear in `fields`.',
    fields: [...FIELDS].sort(),
    field_classes: Object.fromEntries(
      Object.entries(FIELD_CLASSES).map(([k, v]) => [k, { layer: v.layer, fields: [...v.fields].sort() }]),
    ),
    non_transactable: [...NON_TRANSACTABLE].sort(),
    dppa_purposes: Object.fromEntries(
      Object.entries(DPPA_PURPOSES).map(([k, v]) => [k, v.cite]),
    ),
    counterparty_classes: [...COUNTERPARTY_CLASSES].sort(),
  }

  mkdirSync(HERE, { recursive: true })
  writeFileSync(join(HERE, 'grants.json'), `${JSON.stringify(out, null, 2)}\n`)
  writeFileSync(join(HERE, 'vocabulary.json'), `${JSON.stringify(vocabulary, null, 2)}\n`)
  console.log(`wrote ${vectors.length} grant vectors and the published vocabulary to ${HERE}`)
}

await main()
