/**
 * NF-5 conformance — VIN syntax, ISO 3779 check digit, and the NF-2 pseudonym
 * construction. MODULE profile, over `broker/src/vin.js`.
 *
 * Nimbus Foundation NF-5 §8 (Group VC), §4.4 (determinism). NF-WP-1 §1.4, §8.2, §9.5,
 * §12.7.
 *
 * REFUSAL 1 IS THE FRAME. Every export in `vin.js` answers one of exactly two questions:
 * "is this a well-formed name" and "what is the rotating pseudonym for this name".
 * Nothing here authorises anything, and the assertions below are written so that a future
 * export that *did* authorise something would have no test to belong to. The 2015
 * Miller-Valasek Jeep compromise and Curry et al.'s 2023 survey both turned on a VIN being
 * accepted where proof of authority was required; the fix is not to make the VIN secret —
 * it is stamped on the dashboard — but to prove authority separately, which is why this
 * module is deliberately incapable of granting any.
 *
 * DERIVATION, NOT ASSERTION OF FACT (NF-5 §4.4, §4.8). Only one real-world VIN appears
 * below: `1M8GDM9AXKP042788`, the worked example carried by the standard itself, whose
 * check digit is X. Every other VIN is synthetic, generated deterministically as
 * SHA-256(suite_seed || ':' || assertion_id || ':' || i) mapped onto the ISO 3779
 * alphabet, and its expected check digit is computed by the independent reference
 * implementation in this file rather than asserted as a fact about a vehicle that may or
 * may not exist.
 */

