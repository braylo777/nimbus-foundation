test('base64url and base64urlToBytes round-trip every length that matters', async () => {
  for (const length of [1, 2, 3, 4, 15, 16, 31, 32, 33, 64, 65]) {
    const bytes = await derivedBytes('b64', length, length)
    const encoded = base64url(bytes)
    assert.match(encoded, /^[A-Za-z0-9_-]*$/, `padding or standard alphabet leaked: ${encoded}`)
    assert.deepEqual([...base64urlToBytes(encoded)], [...bytes], `round trip failed at ${length}`)
  }
  assert.equal(base64url(new Uint8Array(0)), '')
})

test('base64url never emits +, / or =', async () => {
  // The grant schema pins base64url specifically: a value that round-trips to different
  // bytes on different decoders is a value inside a signature that means two things.
  for (let i = 0; i < 256; i += 1) {
    const encoded = base64url(await derivedBytes('b64-charset', i, 32))
    assert.equal(/[+/=]/.test(encoded), false, encoded)
    assert.equal(encoded.length, 43)
  }
})
