const AUDIENCE_A = 'fleet-operator'
const AUDIENCE_B = 'academic-research'

async function fixedSalt(label) {
  return base64url(await derivedBytes('salt', label, 32))
}

test('[control] the pseudonym is a 32-byte base64url value and is deterministic', async () => {
  const vin = await syntheticVin('pseudonym', 0)
  const salt = await fixedSalt('a')
  const first = await vehiclePseudonym(vin, salt, 7, AUDIENCE_A)
  const second = await vehiclePseudonym(vin, salt, 7, AUDIENCE_A)
  assert.equal(first, second, 'the pseudonym must be reproducible by a party holding the salt')
  assert.equal(first.length, 43)
  assert.match(first, /^[A-Za-z0-9_-]+$/)
  assert.equal(base64urlToBytes(first).length, 32)
})

test('the same VIN and salt under a different AUDIENCE yields a different pseudonym', async () => {
  // Rotation alone still lets two simultaneous counterparties join inside one epoch.
  // Binding to the counterparty class makes that join fail (NF-WP-1 §12.7).
  const vin = await syntheticVin('pseudonym', 1)
  const salt = await fixedSalt('a')
  const a = await vehiclePseudonym(vin, salt, 3, AUDIENCE_A)
  const b = await vehiclePseudonym(vin, salt, 3, AUDIENCE_B)
  assert.notEqual(a, b)
})

test('the same VIN and salt under a different EPOCH yields a different pseudonym', async () => {
  // A stable pseudonym is a permanent correlation handle. Rotation bounds linkability to a
  // single epoch.
  const vin = await syntheticVin('pseudonym', 2)
  const salt = await fixedSalt('a')
  const seen = new Set()
  for (const epoch of [0, 1, 2, 3, 100, 4096]) {
    seen.add(await vehiclePseudonym(vin, salt, epoch, AUDIENCE_A))
  }
  assert.equal(seen.size, 6, 'two epochs collided: rotation is not in the derivation')
})

test('a different salt or a different VIN yields a different pseudonym', async () => {
  const vinA = await syntheticVin('pseudonym', 3)
  const vinB = await syntheticVin('pseudonym', 4)
  const saltA = await fixedSalt('a')
  const saltB = await fixedSalt('b')
  const base = await vehiclePseudonym(vinA, saltA, 1, AUDIENCE_A)
  assert.notEqual(base, await vehiclePseudonym(vinA, saltB, 1, AUDIENCE_A))
  assert.notEqual(base, await vehiclePseudonym(vinB, saltA, 1, AUDIENCE_A))
  assert.notEqual(base, await vehiclePseudonym(vinB, saltB, 1, AUDIENCE_A))
})

test('two VINs differing in one character produce unrelated pseudonyms', async () => {
  const vin = await syntheticVin('pseudonym', 5)
  const salt = await fixedSalt('a')
  const neighbour =
    vin.slice(0, 0) + nextDifferentValue(vin[0]) + vin.slice(1)
  const a = await vehiclePseudonym(vin, salt, 0, AUDIENCE_A)
  const b = await vehiclePseudonym(neighbour, salt, 0, AUDIENCE_A)
  assert.notEqual(a, b)
  // No shared prefix: a shared prefix would let a holder bucket vehicles without the salt.
  assert.notEqual(a.slice(0, 8), b.slice(0, 8))
})

test('the raw VIN is not recoverable from, or present in, the pseudonym', async () => {
  // Refusal 1 at the output boundary. The pseudonym is what travels in a grant payload; if
  // the VIN survived into it, the salted-HMAC construction would be decoration.
  const salt = await fixedSalt('a')
  for (let i = 0; i < 64; i += 1) {
    const vin = await syntheticVin('pseudonym-leak', i)
    const value = await vehiclePseudonym(vin, salt, 0, AUDIENCE_A)
    assert.equal(value.includes(vin), false)
    assert.equal(value.toUpperCase().includes(vin), false)
    for (let start = 0; start + 6 <= 17; start += 1) {
      const fragment = vin.slice(start, start + 6)
      assert.equal(
        value.toUpperCase().includes(fragment),
        false,
        `pseudonym leaks VIN fragment ${fragment}`,
      )
    }
  }
})

test('the VIN is normalised before derivation, so one vehicle has one pseudonym', async () => {
  const vin = await syntheticVin('pseudonym', 6)
  const salt = await fixedSalt('a')
  const canonical = await vehiclePseudonym(vin, salt, 0, AUDIENCE_A)
  for (const variant of [vin.toLowerCase(), `  ${vin}`, `${vin}\t`, ` ${vin.toLowerCase()} `]) {
    assert.equal(await vehiclePseudonym(variant, salt, 0, AUDIENCE_A), canonical, variant)
  }
})

test('a VIN with a bad check digit is still pseudonymisable; a malformed one is not', async () => {
  const vin = await syntheticVin('pseudonym', 7)
  const salt = await fixedSalt('a')
  const badCheck = vin.slice(0, CHECK_INDEX) + nextDifferentValue(vin[CHECK_INDEX]) + vin.slice(CHECK_INDEX + 1)
  assert.equal(typeof (await vehiclePseudonym(badCheck, salt, 0, AUDIENCE_A)), 'string')

  for (const malformed of ['', 'SHORT', '1M8GDM9AXKP04278I', null, undefined, 42, {}]) {
    await assert.rejects(
      () => vehiclePseudonym(malformed, salt, 0, AUDIENCE_A),
      /cannot pseudonymise malformed VIN/,
      String(malformed),
    )
  }
})

test('a salt shorter than 32 DECODED bytes is refused', async () => {
  // Measured in decoded bytes, not characters: a 32-character hex salt is 16 bytes, half
  // the advertised strength, and the VIN space it defends is enumerable from a parking lot.
  const vin = await syntheticVin('pseudonym', 8)
  assert.equal(MIN_SALT_BYTES, 32)

  for (const byteLength of [1, 8, 16, 24, 31]) {
    const short = base64url(await derivedBytes('short-salt', byteLength, byteLength))
    assert.ok(base64urlToBytes(short).length < MIN_SALT_BYTES)
    await assert.rejects(
      () => vehiclePseudonym(vin, short, 0, AUDIENCE_A),
      /at least 32 bytes/,
      `${byteLength}-byte salt accepted`,
    )
  }

  // The boundary is inclusive: exactly 32 bytes is acceptable.
  const exact = base64url(await derivedBytes('exact-salt', 32, 32))
  assert.equal(base64urlToBytes(exact).length, 32)
  assert.equal(typeof (await vehiclePseudonym(vin, exact, 0, AUDIENCE_A)), 'string')
})

test('a non-base64url salt is refused rather than silently mis-measured', async () => {
  const vin = await syntheticVin('pseudonym', 9)
  const thirtyTwoBytes = base64url(await derivedBytes('exact-salt', 32, 32))
  for (const bad of [
    '',
    'a',
    'abcde',
    `${thirtyTwoBytes}=`,
    `${thirtyTwoBytes}+`,
    `${thirtyTwoBytes}/`,
    `${thirtyTwoBytes} `,
    ` ${thirtyTwoBytes}`,
    `${thirtyTwoBytes}\n`,
    'a'.repeat(32), // the hex trap: "32 bytes of hex" is 32 CHARACTERS, i.e. 16 bytes
    null,
    undefined,
    0,
    {},
    [],
    new Uint8Array(32),
  ]) {
    await assert.rejects(
      () => vehiclePseudonym(vin, bad, 0, AUDIENCE_A),
      /salt/,
      `salt accepted: ${String(bad).slice(0, 20)}`,
    )
  }
  // Pin which rule fires on the hex trap. A 32-character hex string is charset-legal
  // base64url, so the charset check passes and the ENTROPY check is the one that saves it —
  // which is the entire reason the minimum is measured in decoded bytes.
  assert.equal(base64urlToBytes('a'.repeat(32)).length, 24)
  await assert.rejects(
    () => vehiclePseudonym(vin, 'a'.repeat(32), 0, AUDIENCE_A),
    /at least 32 bytes/,
  )
})

test('a malformed epoch is refused: it is inside the signed bytes of a grant', async () => {
  const vin = await syntheticVin('pseudonym', 10)
  const salt = await fixedSalt('a')
  for (const bad of [-1, -0.5, 1.5, '0', '1', null, undefined, NaN, Infinity, 2 ** 53, {}, [], true]) {
    await assert.rejects(
      () => vehiclePseudonym(vin, salt, bad, AUDIENCE_A),
      /epoch/,
      `epoch accepted: ${String(bad)}`,
    )
  }
  assert.equal(typeof (await vehiclePseudonym(vin, salt, 0, AUDIENCE_A)), 'string')
  assert.equal(typeof (await vehiclePseudonym(vin, salt, Number.MAX_SAFE_INTEGER, AUDIENCE_A)), 'string')
})

