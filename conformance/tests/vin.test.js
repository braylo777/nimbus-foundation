test('PSEUDONYM_DERIVATION is the single exported construction tag', () => {
  // Exported so NF-2 grants record the construction rather than hard-coding a second copy.
  // Two copies of one security constant drift silently the moment the derivation is
  // versioned: pseudonyms stop matching and it reads as a data problem.
  assert.equal(PSEUDONYM_DERIVATION, 'nf2-pseudonym:v1')
  assert.equal(typeof PSEUDONYM_DERIVATION, 'string')
})

test('generatePseudonymSalt produces salts this module will accept', async () => {
  const vin = await syntheticVin('pseudonym', 12)
  const salts = new Set()
  for (let i = 0; i < 64; i += 1) {
    const salt = generatePseudonymSalt()
    assert.equal(salt.length, 43)
    assert.match(salt, /^[A-Za-z0-9_-]+$/)
    assert.equal(base64urlToBytes(salt).length, MIN_SALT_BYTES)
    salts.add(salt)
  }
  // Uniqueness is the property under test, not a random input to an assertion: a generator
  // that returned a constant would destroy the salt's entire purpose, and 64 collisions-free
  // draws from a 256-bit space is not a coin flip.
  assert.equal(salts.size, 64, 'generatePseudonymSalt repeated a salt')
  assert.equal(typeof (await vehiclePseudonym(vin, generatePseudonymSalt(), 0, AUDIENCE_A)), 'string')
})

