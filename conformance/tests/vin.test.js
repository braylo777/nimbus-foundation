test('I, O and Q are refused at every position', () => {
  const base = '1M8GDM9AXKP042788'
  for (const excluded of ['I', 'O', 'Q']) {
    for (let pos = 0; pos < 17; pos += 1) {
      const mutated = base.slice(0, pos) + excluded + base.slice(pos + 1)
      const result = validateVin(mutated)
      assert.equal(result.syntaxValid, false, mutated)
      assert.equal(result.valid, false)
      assert.equal(result.normalized, null)
      assert.equal(result.checkDigitValid, null)
      assert.equal(result.expectedCheckDigit, null)
      assert.match(result.reason, /outside the ISO 3779 set/)
    }
  }
})

test('anything but exactly 17 characters is refused', () => {
  for (const bad of ['', '1', '1M8GDM9AXKP04278', '1M8GDM9AXKP0427888', 'A'.repeat(100)]) {
    const result = validateVin(bad)
    assert.equal(result.syntaxValid, false, JSON.stringify(bad))
    assert.match(result.reason, /exactly 17 characters/)
  }
})

test('a non-string is refused without coercion', () => {
  for (const bad of [null, undefined, 0, 17, true, {}, [], ['1M8GDM9AXKP042788'], () => {}, 3n]) {
    const result = validateVin(bad)
    assert.equal(result.syntaxValid, false, String(bad))
    assert.equal(result.valid, false)
    assert.match(result.reason, /VIN must be a string/)
  }
})

test('a Latin-lookalike or punctuation character is refused', () => {
  for (const bad of [
    '1M8GDM9AXKP04278а', // Cyrillic a
    '1M8GDM9AXKP04278*',
    '1M8GDM9AXKP04278_',
    '1M8GDM9AXKP0427‍88'.slice(0, 17),
    '1M8GDM9AXKP04278\ud800',
  ]) {
    assert.equal(validateVin(bad).syntaxValid, false, JSON.stringify(bad))
  }
})

test('leading/trailing whitespace and lower case normalise; nothing else does', () => {
  const vin = '1M8GDM9AXKP042788'
  for (const variant of [`  ${vin}`, `${vin}  `, ` ${vin} `, vin.toLowerCase(), `\t${vin}\n`]) {
    const result = validateVin(variant)
    assert.equal(result.syntaxValid, true, JSON.stringify(variant))
    assert.equal(result.normalized, vin)
    assert.equal(result.valid, true)
  }
  // Interior whitespace is not stripped: that would silently accept two different names as
  // one, and the VIN is the index the whole system is keyed on.
  assert.equal(validateVin('1M8GDM9AX KP042788').syntaxValid, false)
})

test('strict:false separates syntax from the check digit instead of collapsing them', async () => {
  // 49 C.F.R. § 565.15 mandates the check digit for the North American market; ISO 3779
  // does not require it universally, so a grey-market vehicle can carry a structurally
  // valid VIN that fails it. Collapsing the two results would make such a vehicle
  // un-enrollable, which is a defect and not a policy.
  const vin = await syntheticVin('ISO3779-strictness', 0)
  const wrongCheck = nextDifferentValue(vin[CHECK_INDEX])
  const bad = vin.slice(0, CHECK_INDEX) + wrongCheck + vin.slice(CHECK_INDEX + 1)

  const lenient = validateVin(bad, { strict: false })
  assert.equal(lenient.valid, true)
  assert.equal(lenient.syntaxValid, true)
  assert.equal(lenient.checkDigitValid, false)
  assert.equal(lenient.expectedCheckDigit, vin[CHECK_INDEX])
  assert.match(lenient.reason, /check digit mismatch/)

  const strict = validateVin(bad)
  assert.equal(strict.valid, false)
  assert.equal(strict.syntaxValid, true)
  assert.equal(validateVin(bad, {}).valid, false, 'strict must default to on')
  assert.equal(validateVin(bad, { strict: true }).valid, false)

  // strict:false never rescues a SYNTAX failure.
  assert.equal(validateVin('NOT-A-VIN', { strict: false }).valid, false)
  assert.equal(validateVin('1M8GDM9AXKP04278I', { strict: false }).valid, false)
})

test('wmi returns the first three characters of a syntactically valid VIN, else null', async () => {
  const vin = await syntheticVin('WMI', 0)
  assert.equal(wmi(vin), vin.slice(0, 3))
  assert.equal(wmi(vin.toLowerCase()), vin.slice(0, 3))
  // A wrong check digit still has a WMI: the WMI is a naming question, not an integrity one.
  const bad = vin.slice(0, CHECK_INDEX) + nextDifferentValue(vin[CHECK_INDEX]) + vin.slice(CHECK_INDEX + 1)
  assert.equal(wmi(bad), vin.slice(0, 3))
  for (const malformed of ['', 'TOO SHORT', null, undefined, 42, '1M8GDM9AXKP04278I']) {
    assert.equal(wmi(malformed), null, String(malformed))
  }
})

test('validateVin returns a verdict and never a credential', () => {
  // Refusal 1, expressed as a shape assertion: the return value has exactly six members and
  // none of them is a key, a token, a URL, or a statement about an owner. A VIN alone must
  // change no access outcome anywhere.
  const result = validateVin('1M8GDM9AXKP042788')
  assert.deepEqual(Object.keys(result).sort(), [
    'checkDigitValid',
    'expectedCheckDigit',
    'normalized',
    'reason',
    'syntaxValid',
    'valid',
  ])
})

