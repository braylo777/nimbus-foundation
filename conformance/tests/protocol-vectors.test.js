/**
 * NF-5 §4.2 — PROTOCOL-profile assertions over published vectors.
 *
 * PROFILE: PROTOCOL. This file imports nothing from `broker/src`, `m0-vin-yield/src` or
 * `m3-drop-compliance/src`. It reads two committed artifacts — `vectors/grants.json` and
 * `vectors/vocabulary.json` — and re-derives every cryptographic claim with code written
 * here: a separately implemented JCS canonicaliser and raw WebCrypto Ed25519.
 *
 * WHY THIS FILE HAS TO EXIST. Every other assertion in the suite calls the reference
 * implementation's exports directly, so the suite as a whole was testing one implementation
 * rather than a specification. NF-5 §4.2 requires the Prime tier to be attainable through the
 * PROTOCOL profile alone: an implementer who shares no code with this repository must still be
 * assessable. A suite that cannot do that is a regression test wearing a standard's clothing.
 *
 * WHAT INDEPENDENCE BUYS, PRECISELY. The canonicaliser and the verifier below were written
 * against RFC 8785 and RFC 8032, not against `jcs.js` and `nf2-grant.js`. If the reference
 * canonicaliser sorted keys by code point instead of code unit, or omitted a key, or the
 * signer signed the wrong bytes, these assertions fail — the two implementations would
 * disagree. What this cannot catch is an error the specification and both implementations
 * share. That residue is real and is stated rather than papered over.
 *
 * The vectors are generated by the reference implementation (see vectors/generate.js), so the
 * POSITIVE vectors inherit its behaviour. The NEGATIVE vectors do not: they are produced by
 * tampering with already-signed bytes, so their invalidity is a fact about Ed25519 rather than
 * an opinion of the generator.
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { webcrypto } from 'node:crypto'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const VECTOR_DIR = resolve(HERE, '..', 'vectors')

const corpus = JSON.parse(readFileSync(join(VECTOR_DIR, 'grants.json'), 'utf8'))
const vocabulary = JSON.parse(readFileSync(join(VECTOR_DIR, 'vocabulary.json'), 'utf8'))

// ------------------------------------------------------- independent JCS (RFC 8785)

/**
 * Minimal RFC 8785 canonicaliser, written for this file.
 *
 * Object keys sort by UTF-16 code unit, which is what JavaScript's default string comparison
 * already does — the distinction from code-POINT ordering only bites above the BMP, and it
 * bites in the direction of surrogate pairs sorting before some BMP characters. Grants are
 * ASCII, so the two agree here; the ordering is spelled out anyway because a canonicaliser
 * that is accidentally right is not a canonicaliser.
 *
 * Only the JSON subset a grant can contain is supported. Anything else throws rather than
 * being guessed at: a canonicaliser that silently coerces is a signature-forgery surface.
 */
function jcs(value) {
  if (value === null) return 'null'
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error('non-finite number is not canonicalisable')
    if (!Number.isSafeInteger(value)) throw new Error(`unsafe integer in vector: ${value}`)
    return String(value)
  }
  if (typeof value === 'string') return JSON.stringify(value)
  if (Array.isArray(value)) return `[${value.map(jcs).join(',')}]`
  if (typeof value === 'object') {
    if (Object.getPrototypeOf(value) !== Object.prototype && Object.getPrototypeOf(value) !== null) {
      throw new Error('only plain objects are canonicalisable')
    }
    const keys = Object.keys(value).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
    return `{${keys.map((k) => `${JSON.stringify(k)}:${jcs(value[k])}`).join(',')}}`
  }
  throw new Error(`uncanonicalisable value of type ${typeof value}`)
}

function b64urlToBytes(s) {
  const padded = s.replace(/-/g, '+').replace(/_/g, '/')
  return new Uint8Array(Buffer.from(padded + '='.repeat((4 - (padded.length % 4)) % 4), 'base64'))
}

/**
 * Verify an Ed25519 signature over the JCS canonicalisation of an object with `signature`
 * omitted. This is the entire NF-2 signing rule, restated independently.
 */
async function verifySignedObject(obj, publicKeyB64url) {
  const unsigned = {}
  for (const [k, v] of Object.entries(obj)) {
    if (k !== 'signature') unsigned[k] = v
  }
  const bytes = new TextEncoder().encode(jcs(unsigned))
  let key
  try {
    key = await webcrypto.subtle.importKey('raw', b64urlToBytes(publicKeyB64url), { name: 'Ed25519' }, false, ['verify'])
  } catch (err) {
    // A malformed key is a failed verification, not a crashed suite.
    return { ok: false, error: String(err) }
  }
  const sig = b64urlToBytes(obj.signature)
  const ok = await webcrypto.subtle.verify({ name: 'Ed25519' }, key, sig, bytes)
  return { ok, error: null }
}

const grantVectors = corpus.vectors.filter((v) => v.grant)
const recordVectors = corpus.vectors.filter((v) => v.record)
const VIN_SHAPED = /\b[A-HJ-NPR-Z0-9]{17}\b/g

// ------------------------------------------------------------------- corpus sanity

test('[control] the vector corpus is non-empty and carries both verdicts', () => {
  // Without this, every "for each vector" assertion below passes against an empty file.
  assert.ok(grantVectors.length >= 4, `expected several grant vectors, got ${grantVectors.length}`)
  assert.ok(recordVectors.length >= 2, `expected several revocation vectors, got ${recordVectors.length}`)
  assert.ok(corpus.vectors.some((v) => v.expected === 'valid'), 'corpus has no positive vector')
  assert.ok(corpus.vectors.some((v) => v.expected === 'invalid'), 'corpus has no negative vector')
})

test('[control] the independent canonicaliser matches RFC 8785 on ordering and escaping', () => {
  assert.equal(jcs({ b: 1, a: 2 }), '{"a":2,"b":1}')
  assert.equal(jcs({ a: [3, 1, 2] }), '{"a":[3,1,2]}', 'array order is significant and preserved')
  assert.equal(jcs({ 'a b': 'q"q' }), JSON.stringify({ 'a b': 'q"q' }), 'quotes escape, spaces do not')
  assert.equal(jcs({ z: 1, A: 2 }), '{"A":2,"z":1}', 'uppercase sorts first by UTF-16 code unit')
  assert.equal(jcs(null), 'null')
  assert.throws(() => jcs(Number.NaN))
  assert.throws(() => jcs(undefined))
  assert.throws(() => jcs(new Date(0)))
})

// -------------------------------------------------------------------- GC (grant core)

test('GC [protocol]: every grant vector reaches its declared verdict under independent verification', async () => {
  for (const v of grantVectors) {
    const { ok } = await verifySignedObject(v.grant, v.signer_public_key)
    assert.equal(
      ok,
      v.expected === 'valid',
      `${v.id}: independent Ed25519 verification says ${ok}, vector declares ${v.expected}` +
        (v.reason ? ` (${v.reason})` : ''),
    )
  }
})

test('GC [protocol]: every grant carries the closed key set with no omissions', () => {
  const expected = [...corpus.constants.grant_keys].sort()
  for (const v of grantVectors) {
    assert.deepEqual(
      Object.keys(v.grant).sort(),
      expected,
      `${v.id}: a grant must carry every declared key, using explicit null where unused — ` +
        'absence and null canonicalise differently, so allowing both gives one grant two commitments',
    )
  }
})

test('GC [protocol]: no grant outlives the published maximum duration', () => {
  for (const v of grantVectors) {
    const life = v.grant.expires_at - v.grant.issued_at
    assert.ok(life > 0, `${v.id}: expiry must follow issuance`)
    assert.ok(
      life <= corpus.constants.max_grant_duration_s,
      `${v.id}: ${life}s exceeds the published ${corpus.constants.max_grant_duration_s}s cap`,
    )
  }
})

// ------------------------------------------------------------- NT (non-transactability)

test('NT [protocol]: the published vocabulary and the forbidden classes are disjoint', () => {
  const fields = new Set(vocabulary.fields)
  const overlap = vocabulary.non_transactable.filter((f) => fields.has(f))
  assert.deepEqual(
    overlap,
    [],
    'a non-transactable class must have no grant type at all, not a field with a deny flag',
  )
  assert.ok(vocabulary.non_transactable.length > 0, 'the forbidden list must not be empty')
})

test('NT [protocol]: no vector names a field outside the closed vocabulary', () => {
  const fields = new Set(vocabulary.fields)
  const forbidden = new Set(vocabulary.non_transactable)
  for (const v of grantVectors) {
    for (const f of v.grant.fields) {
      assert.ok(!forbidden.has(f), `${v.id}: names non-transactable field ${f}`)
      assert.ok(fields.has(f), `${v.id}: names ${f}, which is outside the closed vocabulary`)
    }
  }
})

test('NT [protocol]: every purpose cites a DPPA permissible-use category', () => {
  for (const v of grantVectors) {
    assert.ok(
      Object.hasOwn(vocabulary.dppa_purposes, v.grant.purpose),
      `${v.id}: purpose ${v.grant.purpose} is not a published DPPA category`,
    )
    assert.match(vocabulary.dppa_purposes[v.grant.purpose], /18 U\.S\.C\. § 2721\(b\)/)
  }
})

// ---------------------------------------------------------------- DD (delegation depth)

test('DD [protocol]: a sub-grant strictly decrements its parent depth and records the parent', () => {
  const byId = new Map(corpus.vectors.map((v) => [v.id, v]))
  const subs = corpus.vectors.filter((v) => v.parent_id)
  assert.ok(subs.length > 0, 'corpus must contain at least one delegation chain')

  for (const sub of subs) {
    const parent = byId.get(sub.parent_id)
    assert.ok(parent, `${sub.id}: declares parent ${sub.parent_id}, which is not in the corpus`)
    assert.equal(
      sub.grant.delegation_depth,
      parent.grant.delegation_depth - 1,
      `${sub.id}: depth must decrement by exactly one`,
    )
    assert.equal(sub.grant.parent_grant_id, parent.grant.grant_id, `${sub.id}: parent linkage must be recorded`)
    assert.ok(
      sub.grant.expires_at <= parent.grant.expires_at,
      `${sub.id}: a sub-grant must not outlive its parent`,
    )
  }
})

test('DD [protocol]: depth is bounded and non-negative across the corpus', () => {
  for (const v of grantVectors) {
    assert.ok(Number.isSafeInteger(v.grant.delegation_depth), `${v.id}: depth must be an integer`)
    if (v.expected === 'valid') {
      assert.ok(v.grant.delegation_depth >= 0, `${v.id}: depth must not be negative`)
      assert.ok(
        v.grant.delegation_depth <= corpus.constants.max_delegation_depth,
        `${v.id}: depth exceeds the published maximum`,
      )
    }
  }
})

test('DD [protocol]: a laundered depth fails verification rather than being accepted', async () => {
  const laundered = corpus.vectors.find((v) => v.id === 'DD-LAUNDERED-DEPTH')
  assert.ok(laundered, 'corpus must carry a depth-laundering negative vector')
  const { ok } = await verifySignedObject(laundered.grant, laundered.signer_public_key)
  assert.equal(ok, false, 'raising delegation_depth after signing must invalidate the signature')
})

// ------------------------------------------------------------------- RV (revocation)

test('RV [protocol]: revocation records verify under the owner-held revocation key', async () => {
  for (const v of recordVectors) {
    const { ok } = await verifySignedObject(v.record, v.signer_public_key)
    assert.equal(ok, v.expected === 'valid', `${v.id}: verification ${ok}, declared ${v.expected}`)
  }
})

test('RV [protocol]: a revocation cannot be redirected to another target', async () => {
  const retargeted = corpus.vectors.find((v) => v.id === 'RV-RETARGETED')
  assert.ok(retargeted, 'corpus must carry a retargeting negative vector')
  const { ok } = await verifySignedObject(retargeted.record, retargeted.signer_public_key)
  assert.equal(ok, false, 'the signature covers the target; rewriting it must invalidate the record')
})

test('RV [protocol]: the published staleness bound is internally consistent and within its ceiling', () => {
  const s = corpus.staleness
  assert.ok(s, 'corpus must publish the staleness bound')
  assert.ok(
    s.default_max_decision_age_s <= s.max_permitted_decision_age_s,
    'a default decision age above its own permitted ceiling is a defect',
  )
  assert.ok(s.default_max_decision_age_s > 0, 'a zero bound would make every cached decision stale')

  // The rule, restated here rather than imported: honour iff the decision is neither
  // future-dated nor older than the bound. A cached ALLOW past the bound must be re-derived,
  // which is what stops a revocation from being outrun by a cache.
  for (const c of s.cases) {
    const age = c.now - c.derived_at
    const expected = age >= 0 && age <= c.max_age_s ? 'honour' : 're-derive'
    assert.equal(
      c.expected,
      expected,
      `staleness case (derived_at ${c.derived_at}, now ${c.now}, bound ${c.max_age_s}) declares ` +
        `${c.expected}; the published rule gives ${expected}`,
    )
  }
})

// -------------------------------------------------------- VC (no VIN-to-credential path)

test('VC [protocol]: no published vector contains a raw VIN anywhere in its bytes', () => {
  // The corpus was generated from a real, syntactically valid VIN. If any of it survived into
  // a grant, a revocation record, or a commitment, Refusal 1 has been broken in the artifact
  // that travels furthest — and this is checkable by anyone holding the file.
  for (const v of corpus.vectors) {
    const serialized = JSON.stringify(v)
    const candidates = serialized.match(VIN_SHAPED) ?? []
    for (const candidate of candidates) {
      // Base64url blobs can coincidentally contain 17 uppercase-alnum characters, so a hit is
      // only a violation if it also passes the ISO 3779 check digit — which a real VIN does.
      assert.ok(
        !isVinCheckDigitValid(candidate),
        `${v.id}: contains ${candidate}, which is a check-digit-valid VIN`,
      )
    }
  }
})

test('VC [protocol]: grants identify a vehicle only by an opaque, audience-bound pseudonym', () => {
  for (const v of grantVectors) {
    const ps = v.grant.vehicle_pseudonym
    assert.ok(ps && typeof ps === 'object', `${v.id}: must carry a pseudonym object`)
    assert.deepEqual(Object.keys(ps).sort(), ['audience', 'derivation', 'epoch', 'value'])
    assert.match(ps.value, /^[A-Za-z0-9_-]{43}$/, `${v.id}: pseudonym must be 32 opaque bytes`)
    assert.ok(Number.isSafeInteger(ps.epoch) && ps.epoch >= 0, `${v.id}: epoch must be a safe integer`)
    assert.ok(
      typeof ps.audience === 'string' && ps.audience.length > 0,
      `${v.id}: an unbound pseudonym is a cross-counterparty correlation handle`,
    )
    assert.ok(
      vocabulary.counterparty_classes.includes(ps.audience),
      `${v.id}: audience ${ps.audience} is not a published counterparty class`,
    )
  }
})

test('VC [protocol]: no vector carries a credential-shaped key', () => {
  const FORBIDDEN = /^(token|credential|secret|password|bearer|session|api_?key|access_?token|authorization)$/i
  const walk = (node, path, id) => {
    if (Array.isArray(node)) return node.forEach((n, i) => walk(n, `${path}[${i}]`, id))
    if (node && typeof node === 'object') {
      for (const [k, val] of Object.entries(node)) {
        assert.ok(!FORBIDDEN.test(k), `${id}: credential-shaped key "${k}" at ${path}`)
        walk(val, `${path}.${k}`, id)
      }
    }
  }
  for (const v of corpus.vectors) walk(v, '$', v.id)
})

/** ISO 3779 check digit, reimplemented here so the VC scan does not import the module under test. */
function isVinCheckDigitValid(vin) {
  if (!/^[A-HJ-NPR-Z0-9]{17}$/.test(vin)) return false
  const t = { A: 1, B: 2, C: 3, D: 4, E: 5, F: 6, G: 7, H: 8, J: 1, K: 2, L: 3, M: 4, N: 5, P: 7, R: 9, S: 2, T: 3, U: 4, V: 5, W: 6, X: 7, Y: 8, Z: 9 }
  const w = [8, 7, 6, 5, 4, 3, 2, 10, 0, 9, 8, 7, 6, 5, 4, 3, 2]
  let sum = 0
  for (let i = 0; i < 17; i += 1) {
    const ch = vin[i]
    sum += (ch >= '0' && ch <= '9' ? Number(ch) : t[ch]) * w[i]
  }
  const r = sum % 11
  return vin[8] === (r === 10 ? 'X' : String(r))
}
